function squareDimensions(html) {
  return html
    .replaceAll("width=1920, height=1080", "width=1080, height=1080")
    .replaceAll("width: 1920px;", "width: 100%;")
    .replaceAll("height: 1080px;", "height: 100%;")
    .replaceAll('data-width="1920"', 'data-width="1080"');
}

function appendStyle(html, css) {
  const marker = "  </style>";
  const index = html.indexOf(marker);
  if (index < 0) throw new Error("Could not find the primary style block");
  return `${html.slice(0, index)}\n\n    /* Square 1080×1080 reflow. Generated by tools/build-square-variant.mjs. */\n${css}\n${html.slice(index)}`;
}

